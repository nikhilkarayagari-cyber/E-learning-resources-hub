values ('course-assets', 'course-assets', true, 52428800, array['image/jpeg','image/png','image/webp','application/pdf','video/mp4'])
on conflict (id) do update set public = true, file_size_limit = 52428800;
drop policy if exists "course assets public read" on storage.objects;
create policy "course assets public read" on storage.objects for select using (bucket_id = 'course-assets');
drop policy if exists "admins upload course assets" on storage.objects;
create policy "admins upload course assets" on storage.objects for insert to authenticated with check (bucket_id = 'course-assets' and public.is_admin());
drop policy if exists "admins update course assets" on storage.objects;
create policy "admins update course assets" on storage.objects for update to authenticated using (bucket_id = 'course-assets' and public.is_admin()) with check (bucket_id = 'course-assets' and public.is_admin());
drop policy if exists "admins delete course assets" on storage.objects;
create policy "admins delete course assets" on storage.objects for delete to authenticated using (bucket_id = 'course-assets' and public.is_admin());

