-- E-Learning Resource Hub: Supabase schema, demo courses, roles, and RLS.
-- Run the entire file in Supabase Dashboard → SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  full_name text not null default 'Learner',
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  level text not null default 'Beginner' check (level in ('Beginner','Intermediate','Advanced')),
  instructor text not null,
  duration text not null default '4h 00m',
  lessons integer not null default 12 check (lessons >= 0),
  rating numeric(2,1) not null default 4.7 check (rating >= 0 and rating <= 5),
  students integer not null default 0 check (students >= 0),
  price text not null default 'Free',
  color text not null default 'violet',
  icon text not null default '✦',
  description text not null,
  tags text[] not null default '{}',
  featured boolean not null default false,
  thumbnail_path text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  progress integer not null default 0 check (progress between 0 and 100),
  enrolled_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, course_id)
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  description text not null default '',
  content_url text,
  resource_path text,
  position integer not null default 1,
  created_at timestamptz not null default now(),
  unique(course_id, position)
);

create table if not exists public.lesson_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed_at timestamptz not null default now(),
  unique(user_id, lesson_id)
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin') $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    lower(new.email),
    coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'), ''), split_part(new.email, '@', 1)),
    case when lower(new.email) = '257r1a6629genai@gmail.com' then 'admin' else 'student' end
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.courses enable row level security;
alter table public.enrollments enable row level security;
alter table public.lessons enable row level security;
alter table public.lesson_completions enable row level security;

drop policy if exists "profiles read self or admin" on public.profiles;
create policy "profiles read self or admin" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
drop policy if exists "courses readable by everyone" on public.courses;
create policy "courses readable by everyone" on public.courses for select to anon, authenticated using (true);
drop policy if exists "admins insert courses" on public.courses;
create policy "admins insert courses" on public.courses for insert to authenticated with check (public.is_admin());
drop policy if exists "admins update courses" on public.courses;
create policy "admins update courses" on public.courses for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins delete courses" on public.courses;
create policy "admins delete courses" on public.courses for delete to authenticated using (public.is_admin());

drop policy if exists "students read own enrollments" on public.enrollments;
create policy "students read own enrollments" on public.enrollments for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "students enroll self" on public.enrollments;
create policy "students enroll self" on public.enrollments for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "students update own progress" on public.enrollments;
create policy "students update own progress" on public.enrollments for update to authenticated using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
drop policy if exists "admins manage lessons" on public.lessons;
create policy "lessons readable by everyone" on public.lessons for select to anon, authenticated using (true);
create policy "admins insert lessons" on public.lessons for insert to authenticated with check (public.is_admin());
create policy "admins update lessons" on public.lessons for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins delete lessons" on public.lessons for delete to authenticated using (public.is_admin());
drop policy if exists "users read own completions" on public.lesson_completions;
create policy "users read own completions" on public.lesson_completions for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "users complete own lessons" on public.lesson_completions for insert to authenticated with check (user_id = auth.uid());
create policy "users remove own completions" on public.lesson_completions for delete to authenticated using (user_id = auth.uid() or public.is_admin());

